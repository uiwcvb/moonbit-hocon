import fs from 'node:fs';
const saved=JSON.parse(fs.readFileSync(new URL('../evidence/value-reference-vectors.json',import.meta.url),'utf8')),q=JSON.stringify;
let output=`// Independent Lightbend Config 1.4.9 results; generated by tools/generate-value-tests.mjs.
///|
fn value_native_create(source : String) -> @hocon.Value raise {
  @hocon.object_get(@hocon.parse_unresolved("v=" + source), "v").unwrap()
}
///|
fn value_native_attempt(work : () -> Json raise) -> Json {
  Json::object({"accepted":true,"value":work()}) catch { _ => Json::object({"accepted":false}) }
}
///|
fn value_native_snapshot(value : @hocon.Value) -> Json {
  Json::object({"type":value_native_attempt(() => @hocon.value_type(value).to_json()),
    "unwrapped":value_native_attempt(() => @json.parse(@hocon.value_unwrapped(value).to_json_string()))})
}
`;
let count=0;
for(let i=0;i<saved.requests.length;i++){
 const req=saved.requests[i],ref=saved.references[i];
 if(!ref.accepted)continue;
 const pair=req.calls[0]?.op==='new'&&req.calls[2]?.op==='equals';
 if(pair){
  output+=`\n///|\ntest "native value equality ${i}" {\n let a = value_native_create(${q(req.calls[0].source)})\n let b = value_native_create(${q(req.calls[1].source)})\n`;
  const operations=['@hocon.value_equals(a,b)','@hocon.value_equals(b,a)','@hocon.value_hash(a)','@hocon.value_hash(b)'];
  operations.forEach((op,n)=>output+=` assert_eq(value_native_attempt(() => (${op}).to_json()),@json.parse(${q(JSON.stringify(ref.value.results[n+2]))}))\n`);
  output+='}\n';count++;continue;
 }
 const supported=new Set(['new','fallback','config-fallback','at-key','at-path','get-key','only-key','without-key','with-value','resolve']);
 if(!(req.source==='{}'&&req.calls[0]?.op==='new')&&!req.calls.some(c=>c.op==='config-fallback'))continue;
 if(!req.calls.every(c=>supported.has(c.op)))continue;
 output+=`\n///|\ntest "native value fallback state ${i}" {\n let values : Array[@hocon.Value] = [@hocon.parse_unresolved(${q(req.source)})]\n let results : Array[Json] = []\n`;
 for(const c of req.calls){
  const value=`values[${c.target??0}]`,other=`values[${c.other??c.target??0}]`;
  let op;
  switch(c.op){
   case 'new':op=`value_native_create(${q(c.source)})`;break;
   case 'fallback':op=`@hocon.value_with_fallback(${value},${other})`;break;
   case 'config-fallback':op=c.asConfig?`{ if @hocon.value_type(${other}) != "OBJECT" { raise Failure("expected config") }; @hocon.with_fallback(${value},${other}) }`:`@hocon.with_fallback(${value},${other})`;break;
   case 'at-key':op=`@hocon.at_key(${value},${q(c.key)})`;break;
   case 'at-path':op=`@hocon.at_path(${value},${q(c.key)})`;break;
   case 'get-key':op=`@hocon.object_get(${value},${q(c.key)}).unwrap()`;break;
   case 'only-key':op=`@hocon.with_only_key(${value},${q(c.key)})`;break;
   case 'without-key':op=`@hocon.without_key(${value},${q(c.key)})`;break;
   case 'with-value':op=`@hocon.with_key_value(${value},${q(c.key)},${other})`;break;
   case 'resolve':op=`@hocon.resolve(${value},allow_unresolved=${c.allowUnresolved??false})`;break;
  }
  // Failed prior operations can make later IDs invalid. Explicitly reject them
  // rather than letting a test panic mask the native accepted/rejected result.
  output+=` results.push(value_native_attempt(() => {\n if values.length() <= ${Math.max(c.target??0,c.other??0)} { raise Failure("missing prior value") }\n let next = ${op}\n let index = values.length()\n values.push(next)\n index.to_json()\n }))\n`;
 }
 output+=` assert_eq(Json::object({"results":results.to_json(),"final":values.map(value_native_snapshot).to_json()}),@json.parse(${q(JSON.stringify(ref.value))}))\n}\n`;
 count++;
}
const names=[];
output=output.replace(/test "native value (?:equality|fallback state) (\d+)" \{/g,(_all,id)=>{const name='value_native_case_'+id;names.push(name);return `fn ${name}() -> Unit raise {`;});
// Keep the compiler-generated test-dispatch segment below its line limit.
// Every native program remains a separate function/assertion context.
for(let start=0;start<names.length;start+=64)output+=`\n///|\ntest "native value program batch ${start/64}" {\n${names.slice(start,start+64).map(name=>'  '+name+'()').join('\n')}\n}\n`;
fs.writeFileSync(new URL('../value_reference_test.mbt',import.meta.url),output);
console.log(count+' independent value equality/fallback core tests generated');
